// ─── Business type detection from quick reply text ───────────────────────────

export function detectBusinessType(text: string): BusinessType | null {
  const t = text.toLowerCase().trim();
  if (t.includes("อาหาร") || t.includes("ร้านอาหาร") || t.includes("restaurant")) return "restaurant";
  if (t.includes("ออนไลน์") || t.includes("shopee") || t.includes("lazada") || t.includes("ขายของ")) return "online_shop";
  if (t.includes("คลินิก") || t.includes("หมอ") || t.includes("สปา") || t.includes("นวด")) return "clinic";
  if (t.includes("ความงาม") || t.includes("เสริมสวย") || t.includes("ทำผม") || t.includes("เล็บ") || t.includes("beauty")) return "beauty";
  if (t.includes("อื่น")) return "other";
  return null;
}

